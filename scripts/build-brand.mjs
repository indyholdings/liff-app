// Builds a branded copy of the staff UI.
//
//   node scripts/build-brand.mjs <brand>          e.g. globallink
//
// Reads brands/<brand>/brand.json and writes
//   dist/<brand>/extension/            loadable unpacked in Chrome (manifest name and icons, brand.js,
//                                      logos under brand/, fonts under brand/fonts/ + brand/fonts.css)
//   dist/<brand>/staff.html            the mobile staff page; dist/<brand>/ can be hosted as it is
//   dist/<brand>/<brand>-extension.zip the extension folder, zipped
// Node built-ins only. The source extension/ folder is never modified.

import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brandId = process.argv[2];
if (!brandId || !/^[a-z0-9][a-z0-9-]*$/.test(brandId)) {
  console.error('usage: node scripts/build-brand.mjs <brand>   (a folder name under brands/)');
  process.exit(2);
}
const brandDir = path.join(ROOT, 'brands', brandId);
const jsonPath = path.join(brandDir, 'brand.json');
if (!fs.existsSync(jsonPath)) {
  console.error('not found: ' + path.relative(ROOT, jsonPath));
  process.exit(2);
}
const brand = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
for (const key of ['id', 'name', 'theme']) {
  if (typeof brand[key] !== 'string' || !brand[key]) { console.error(`brand.json: "${key}" is required`); process.exit(2); }
}

const out = path.join(ROOT, 'dist', brandId);
const ext = path.join(out, 'extension');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

// A file named in brand.json, resolved inside the brand folder (never outside it).
function brandFile(rel, what) {
  const file = path.resolve(brandDir, String(rel));
  if (!file.startsWith(brandDir + path.sep)) throw new Error(`brand.json: ${what} points outside brands/${brandId}/`);
  if (!fs.existsSync(file)) throw new Error(`brand.json: ${what} not found: ${rel}`);
  return file;
}

// 1. the extension, minus the dev tools
fs.cpSync(path.join(ROOT, 'extension'), ext, {
  recursive: true,
  filter: (src) => path.relative(path.join(ROOT, 'extension'), src).split(path.sep)[0] !== 'dev',
});

// 2. logos → extension/brand/
fs.mkdirSync(path.join(ext, 'brand'), { recursive: true });
const runtime = { id: brand.id, name: brand.name, theme: brand.theme };
if (brand.tagline) runtime.tagline = String(brand.tagline);
for (const key of ['logo_mark', 'logo_mark_on_dark', 'logo_landscape', 'logo_landscape_on_dark']) {
  if (!brand[key]) continue;
  const src = brandFile(brand[key], key);
  fs.copyFileSync(src, path.join(ext, 'brand', path.basename(src)));
  runtime[key] = 'brand/' + path.basename(src);
}

// 3. fonts → extension/brand/fonts/ and a stylesheet that declares them
// File names follow @fontsource: <family>-<subset>-<weight>-<style>.woff2
const UNICODE_RANGE = {
  thai: 'U+02D7,U+0303,U+0331,U+0E01-0E5B,U+200C-200D,U+25CC',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};
const fontsDir = path.join(brandDir, 'fonts');
let fontCount = 0;
if (fs.existsSync(fontsDir)) {
  const faces = [];
  fs.mkdirSync(path.join(ext, 'brand', 'fonts'), { recursive: true });
  for (const name of fs.readdirSync(fontsDir).sort()) {
    const src = path.join(fontsDir, name);
    const m = /^([a-z0-9]+)-(thai|latin)-(\d{3})-(normal|italic)\.woff2$/.exec(name);
    if (!m) {
      // licence and readme files travel with the fonts
      if (/\.(txt|md)$/i.test(name) || /^(LICENSE|OFL)/i.test(name)) fs.copyFileSync(src, path.join(ext, 'brand', 'fonts', name));
      continue;
    }
    fs.copyFileSync(src, path.join(ext, 'brand', 'fonts', name));
    const family = m[1][0].toUpperCase() + m[1].slice(1);
    faces.push(`@font-face { font-family: "${family}"; font-style: ${m[4]}; font-weight: ${m[3]}; font-display: swap; src: url(fonts/${name}) format("woff2"); unicode-range: ${UNICODE_RANGE[m[2]]}; }`);
    fontCount++;
  }
  if (faces.length) {
    fs.writeFileSync(path.join(ext, 'brand', 'fonts.css'), `/* Generated by scripts/build-brand.mjs for "${brand.id}". Do not edit. */\n` + faces.join('\n') + '\n');
    runtime.fonts_css = 'brand/fonts.css';
  }
}

// 4. brand.js
fs.writeFileSync(path.join(ext, 'brand.js'),
  `/* Generated by scripts/build-brand.mjs from brands/${brand.id}/brand.json. Do not edit. */\n` +
  `window.SIDECAR_BRAND = ${JSON.stringify(runtime, null, 2)};\n`);

// 5. manifest: name, description, icons, and the brand files the panel and the toggle load
const manifestPath = path.join(ext, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
manifest.name = String(brand.extension_name || brand.name);
manifest.short_name = String(brand.short_name || (brand.name.length > 12 ? brand.name.split(/\s+/)[0] : brand.name)).slice(0, 12);
if (brand.extension_description) manifest.description = String(brand.extension_description);
if (manifest.action) manifest.action.default_title = brand.name + ' — ตั้งค่า';
if (brand.icons) {
  manifest.icons = {};
  for (const size of Object.keys(brand.icons)) {
    const src = brandFile(brand.icons[size], 'icons.' + size);
    fs.copyFileSync(src, path.join(ext, 'icons', `icon${size}.png`));
    manifest.icons[size] = `icons/icon${size}.png`;
  }
}
for (const entry of manifest.web_accessible_resources || []) {
  for (const res of ['brand/*', 'brand/fonts/*']) if (!entry.resources.includes(res)) entry.resources.push(res);
}
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

// 6. the mobile staff page, next to the extension folder it loads its UI from
fs.copyFileSync(path.join(ROOT, 'staff.html'), path.join(out, 'staff.html'));

// 7. zip of the extension folder
const zipPath = path.join(out, `${brandId}-extension.zip`);
function listFiles(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(full, base) : [path.relative(base, full).split(path.sep).join('/')];
  });
}
function storeOnlyZip(dir, target) {
  // Minimal zip writer (no compression) for machines without the `zip` command.
  const parts = [];
  const central = [];
  let offset = 0;
  for (const rel of listFiles(dir)) {
    const data = fs.readFileSync(path.join(dir, rel));
    const name = Buffer.from(rel, 'utf8');
    const crc = zlib.crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(0, 8); local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12);
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(data.length, 18); local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26); local.writeUInt16LE(0, 28);
    parts.push(local, name, data);
    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(20, 4); cd.writeUInt16LE(20, 6); cd.writeUInt16LE(0x0800, 8);
    cd.writeUInt16LE(0, 10); cd.writeUInt16LE(0, 12); cd.writeUInt16LE(0x21, 14);
    cd.writeUInt32LE(crc, 16); cd.writeUInt32LE(data.length, 20); cd.writeUInt32LE(data.length, 24);
    cd.writeUInt16LE(name.length, 28); cd.writeUInt32LE(offset, 42);
    central.push(cd, name);
    offset += local.length + name.length + data.length;
  }
  const cdBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  const count = central.length / 2;
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(count, 8); end.writeUInt16LE(count, 10);
  end.writeUInt32LE(cdBuf.length, 12); end.writeUInt32LE(offset, 16);
  fs.writeFileSync(target, Buffer.concat([...parts, cdBuf, end]));
}
const zipped = spawnSync('zip', ['-q', '-r', '-X', zipPath, '.'], { cwd: ext });
if (zipped.status !== 0) {
  fs.rmSync(zipPath, { force: true });
  storeOnlyZip(ext, zipPath);
}

const rel = (p) => path.relative(ROOT, p);
console.log(`Built brand "${brand.id}" (${brand.name})`);
console.log(`  extension  ${rel(ext)}/   — load unpacked in chrome://extensions`);
console.log(`  staff page ${rel(path.join(out, 'staff.html'))}   — host ${rel(out)}/ as it is`);
console.log(`  zip        ${rel(zipPath)}   (${Math.round(fs.statSync(zipPath).size / 1024)} KB, ${fontCount} font files)`);
